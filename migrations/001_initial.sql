CREATE TABLE IF NOT EXISTS sources (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 name TEXT NOT NULL,
 url TEXT NOT NULL UNIQUE,
 enabled BOOLEAN NOT NULL DEFAULT FALSE,
 problem TEXT NOT NULL DEFAULT ''
);
CREATE TABLE IF NOT EXISTS jobs (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 url TEXT NOT NULL UNIQUE,
 source_id BIGINT REFERENCES sources(id) ON DELETE SET NULL,
 title TEXT NOT NULL DEFAULT '', company TEXT NOT NULL DEFAULT '',
 description TEXT NOT NULL DEFAULT '', deadline TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL DEFAULT 'Не откликался',
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS jobs_updated_at_idx ON jobs(updated_at DESC);
CREATE TABLE IF NOT EXISTS job_history (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE,
 snapshot JSONB NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS job_history_job_idx ON job_history(job_id, created_at DESC);
CREATE TABLE IF NOT EXISTS checks (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 source_id BIGINT REFERENCES sources(id) ON DELETE SET NULL,
 error TEXT NOT NULL DEFAULT '', created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS checks_source_idx ON checks(source_id, created_at DESC);
CREATE TABLE IF NOT EXISTS job_evidence (
 job_url TEXT NOT NULL REFERENCES jobs(url) ON DELETE CASCADE,
 page_url TEXT NOT NULL,
 first_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
 last_seen TIMESTAMPTZ NOT NULL DEFAULT now(),
 PRIMARY KEY (job_url,page_url)
);
CREATE TABLE IF NOT EXISTS telegram_tokens (
 token_hash BYTEA PRIMARY KEY,
 expires_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE IF NOT EXISTS telegram_link (
 singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
 chat_id BIGINT NOT NULL UNIQUE
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 event_key TEXT NOT NULL UNIQUE,
 message TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','sending','sent','unknown')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS notifications_pending_idx ON notifications(id) WHERE state='pending';
CREATE TABLE IF NOT EXISTS preferences (
 singleton BOOLEAN PRIMARY KEY DEFAULT TRUE CHECK (singleton),
 data JSONB NOT NULL
);
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS location TEXT NOT NULL DEFAULT '';
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS work_mode TEXT NOT NULL DEFAULT '';
CREATE INDEX IF NOT EXISTS checks_created_idx ON checks(created_at DESC);
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS offer_type TEXT NOT NULL DEFAULT '';
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS level TEXT NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS telegram_updates (
 update_id BIGINT PRIMARY KEY,
 received_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
